// Regenerate lib/emoji_data.v with Swift's Unicode scalar properties:
// swift tools/unicode-width.swift > lib/emoji_data.v
import Foundation

func ranges(_ matches: (Unicode.Scalar.Properties) -> Bool) -> [(UInt32, UInt32)] {
  var result: [(UInt32, UInt32)] = []
  for value: UInt32 in 0...0x10ffff {
    guard let scalar = Unicode.Scalar(value), matches(scalar.properties) else { continue }
    if let last = result.last, last.1 + 1 == value { result[result.count - 1].1 = value }
    else { result.append((value, value)) }
  }
  return result
}

print("module vtk\n\n// Generated by tools/unicode-width.swift from Unicode emoji properties.")
for (name, intervals) in [
  ("emoji_presentation", ranges { $0.isEmojiPresentation }),
  ("emoji_base", ranges { $0.isEmoji }),
] {
  print("const \(name) = [")
  for (first, last) in intervals {
    print("\tRuneRange{0x\(String(first, radix: 16)), 0x\(String(last, radix: 16))},")
  }
  print("]\n")
}
