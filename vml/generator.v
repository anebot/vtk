module main

import json2
import strings

struct Template {
	module_name string = 'main'
	imports     []string
	params      string
	result      string
	property    string
	properties  map[string]string
	widgets     map[string]Rule
}

struct Rule {
	create     string
	add        string
	defaults   map[string]string
	properties map[string]string
}

fn read_template(source string) !Template {
	template := json2.decode[Template](source)!
	if template.result == '' || template.widgets.len == 0 {
		return error('template needs a result type and widget rules')
	}
	for tag, rule in template.widgets {
		if rule.create == '' {
			return error('template widget ${tag} needs a create rule')
		}
	}
	return template
}

// Substitute once, so strings and V expressions containing {{...}} stay literal.
fn expand(pattern string, values map[string]string, mut used []string) !string {
	mut out := strings.new_builder(pattern.len)
	mut rest := pattern
	for {
		start := rest.index('{{') or { break }
		out.write_string(rest[..start])
		rest = rest[start + 2..]
		end := rest.index('}}') or { return error('unclosed template placeholder') }
		key := rest[..end]
		value := values[key] or { return error('missing template value ${key}') }
		out.write_string(value)
		used << key
		rest = rest[end + 2..]
	}
	out.write_string(rest)
	return out.str()
}

struct Generator {
	template Template
	source   string
	file     string
mut:
	ids          map[string]bool
	declarations []string
	statements   []string
	count        int
}

fn (g &Generator) fail(node Node, message string) IError {
	return diagnostic(g.source, g.file, node.pos, message)
}

fn (mut g Generator) names(mut node Node) ! {
	if node.id == '' {
		node.id = 'vml_${g.count}'
	}
	g.count++
	if node.id in g.ids || node.id == 'app' {
		return g.fail(node, 'duplicate or reserved widget identifier ${node.id}')
	}
	g.ids[node.id] = true
	for mut child in node.children {
		g.names(mut child)!
	}
}

fn (mut g Generator) emit(node Node, parent string, add string) ! {
	rule := g.template.widgets[node.tag] or {
		return g.fail(node, 'unknown widget ${node.tag}')
	}
	if node.children.len > 0 && rule.add == '' {
		return g.fail(node, '${node.tag} does not accept children')
	}
	mut values := rule.defaults.clone()
	for attr in node.attrs {
		values[attr.name] = attr.value
	}
	values['id'] = node.id
	values['parent'] = parent
	values['child'] = node.id
	mut used := []string{}
	creation := expand(rule.create, values, mut used) or {
		return g.fail(node, '${node.tag}: ${err}')
	}
	attachment := expand(add, values, mut used) or {
		return g.fail(node, '${node.tag}: ${err}')
	}
	g.declarations << 'mut ${node.id} := ${creation}'
	for attr in node.attrs {
		if attr.name in used {
			continue
		}
		pattern := rule.properties[attr.name] or {
			g.template.properties[attr.name] or { g.template.property }
		}
		if pattern == '' {
			return g.fail(node, 'unsupported property ${attr.name} on ${node.tag}')
		}
		mut property_values := values.clone()
		property_values['name'] = attr.name
		property_values['value'] = attr.value
		mut property_used := []string{}
		g.statements << expand(pattern, property_values, mut property_used) or {
			return g.fail(node, '${node.tag}.${attr.name}: ${err}')
		}
	}
	for child in node.children {
		g.emit(child, node.id, rule.add)!
	}
	if attachment != '' {
		g.statements << attachment
	}
	g.statements << node.code
}

fn generate(source string, file string, function_name string, template Template) !string {
	if !identifier(function_name) {
		return error('invalid builder function name ${function_name}')
	}
	mut root := parse(source, file)!
	mut g := Generator{ template: template, source: source, file: file }
	g.names(mut root)!
	g.emit(root, '', '')!
	mut out := strings.new_builder(1024)
	out.writeln('// Generated by vmlc. Edit the .vml source instead.')
	out.writeln('module ${template.module_name}\n')
	for name in template.imports {
		out.writeln('import ${name}')
	}
	out.writeln('\npub fn ${function_name}(${template.params}) ${template.result} {')
	for statement in g.declarations {
		out.writeln('\t${statement}')
	}
	for statement in g.statements {
		for line in statement.split_into_lines() {
			out.writeln('\t${line}')
		}
	}
	out.writeln('\treturn ${root.id}\n}')
	return out.str()
}
